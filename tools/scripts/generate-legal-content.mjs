import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { extractHeadings, renderMarkdown } from './generate-blog-content.mjs';

const ROOT = process.cwd();

const GENERATED_TS = path.join(
  ROOT,
  'apps/web/src/app/pages/legal/legal-content.generated.ts'
);

const DOCUMENTS = [
  {
    key: 'privacy',
    path: '/polityka-prywatnosci',
    source: 'docs/legal/POLITYKA-PRYWATNOSCI.md',
    englishSource: 'docs/legal/PRIVACY-POLICY.en.md',
    englishDescription:
      'How the hosted Spendist service processes and protects personal data.',
    description:
      'Polityka prywatności hostowanej aplikacji Spendist opisująca przetwarzanie i ochronę danych użytkowników.',
  },
  {
    key: 'terms',
    path: '/regulamin',
    source: 'docs/legal/REGULAMIN.md',
    englishSource: 'docs/legal/TERMS.en.md',
    englishDescription: 'Terms for using the free hosted Spendist service.',
    description: 'Regulamin korzystania z hostowanej aplikacji Spendist.',
  },
];

function titleFrom(markdown, source) {
  const title = /^#\s+(.+)$/m.exec(markdown)?.[1]?.trim();

  if (!title) throw new Error(`${source}: expected a level-one title.`);

  return title;
}

function documentVersion(markdown, source) {
  const version =
    /^\*\*(?:Wersja|Version) (\d+\.\d+) — \d{4}-\d{2}-\d{2}\*\*$/m.exec(
      markdown
    )?.[1];

  if (!version)
    throw new Error(`${source}: expected a dated document version.`);

  return version;
}

function generatedTypescript(documents, englishDocuments) {
  return `export interface LegalDocument {
  readonly key: 'privacy' | 'terms';
  readonly path: string;
  readonly title: string;
  readonly description: string;
  readonly version: string;
  readonly html: string;
}

// Generated by tools/scripts/generate-legal-content.mjs. Do not edit manually.
export const LEGAL_VERSION = ${JSON.stringify(documents[0].version)};

export const LEGAL_DOCUMENTS: Record<LegalDocument['key'], LegalDocument> = ${JSON.stringify(
    Object.fromEntries(documents.map((document) => [document.key, document])),
    null,
    2
  )};

export const LEGAL_DOCUMENTS_EN: Record<LegalDocument['key'], LegalDocument> = ${JSON.stringify(
    Object.fromEntries(
      englishDocuments.map((document) => [document.key, document])
    ),
    null,
    2
  )};
`;
}

async function readDocuments(english) {
  return Promise.all(
    DOCUMENTS.map(async (document) => {
      const source = english ? document.englishSource : document.source;
      const markdown = await readFile(path.join(ROOT, source), 'utf8');

      return {
        key: document.key,
        path: document.path,
        title: titleFrom(markdown, source),
        description: english
          ? document.englishDescription
          : document.description,
        version: documentVersion(markdown, source),
        html: renderMarkdown(markdown, extractHeadings(markdown)),
      };
    })
  );
}

async function output() {
  const [documents, englishDocuments] = await Promise.all([
    readDocuments(false),
    readDocuments(true),
  ]);

  for (const document of documents) {
    if (
      document.version !== documents[0].version ||
      englishDocuments.find(
        (englishDocument) => englishDocument.key === document.key
      )?.version !== document.version
    ) {
      throw new Error(`Document versions differ for ${document.key}.`);
    }
  }

  return generatedTypescript(documents, englishDocuments);
}

async function main() {
  const check = process.argv.includes('--check');
  const generated = await output();

  if (check) {
    const current = await readFile(GENERATED_TS, 'utf8').catch(() => '');

    if (current !== generated) {
      throw new Error(
        'Generated legal content is stale. Run npm run legal:generate.'
      );
    }

    console.log('Legal content is current.');

    return;
  }

  await mkdir(path.dirname(GENERATED_TS), { recursive: true });
  await writeFile(GENERATED_TS, generated);
  console.log('Legal content generated.');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
